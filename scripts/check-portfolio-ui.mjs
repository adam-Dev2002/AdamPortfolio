import { chromium } from 'playwright'
import assert from 'node:assert/strict'

const browser = await chromium.launch({ channel: 'chrome', headless: true })
const errors = []
try {
  for (const viewport of [{ width: 1440, height: 900 }, { width: 390, height: 844 }]) {
    const page = await browser.newPage({ viewport })
    page.on('pageerror', error => errors.push(error.message))
    const scroll = () => page.evaluate(() => innerWidth >= 1100 ? document.getElementById('main-content').scrollTop : document.body.style.position === 'fixed' ? -parseFloat(document.body.style.top) : window.scrollY)
    const wheelAtContent = async (amount) => {
      await page.mouse.move(viewport.width - 55, 350)
      await page.mouse.wheel(0, amount)
      await page.waitForTimeout(400)
    }
    await page.goto('http://127.0.0.1:5178/', { waitUntil: 'networkidle' })
    for (const [label, href] of Object.entries({ LinkedIn: 'https://www.linkedin.com/in/adam-romas', Facebook: 'https://www.facebook.com/adam.rubia.2025/', Upwork: 'https://www.upwork.com/freelancers/~01a360ba6c836da36b?viewMode=1', GitHub: 'https://github.com/adam-Dev2002' })) {
      assert.equal(await page.locator(`.rail__social[aria-label="${label}"]`).getAttribute('href'), href)
    }
    await page.waitForFunction(() => !document.documentElement.classList.contains('is-intro'))
    await page.locator('a[href="/projects"]:visible').first().click()
    await page.getByRole('heading', { name: 'Projects built to be useful.' }).waitFor()
    assert.equal(await page.locator('.portfolio-card').count(), 7)
    const geometry = await page.locator('.portfolio-card').evaluateAll(cards => cards.map(card => {
      const image = card.querySelector('.portfolio-card__media').getBoundingClientRect()
      const body = card.querySelector('.portfolio-card__body').getBoundingClientRect()
      const box = card.getBoundingClientRect()
      return { overlap: image.bottom > body.top + 1, outside: body.bottom > box.bottom + 1 }
    }))
    assert(geometry.every(card => !card.overlap && !card.outside), 'Card images and text must not overlap or escape their borders')
    await page.getByRole('button', { name: 'Preview PH WFH Job Finder — AI Limited Version', exact: true }).click()
    const workflowDialog = page.locator('dialog.project-preview')
    await workflowDialog.locator('img').evaluate(img => img.decode())
    assert.equal(await workflowDialog.locator('img').evaluate(img => img.naturalWidth), 7000)
    assert(await workflowDialog.locator('.project-preview__image').evaluate(el => el.clientWidth) >= 1100, 'Workflow preview must open at a readable size')
    await workflowDialog.getByRole('button', { name: 'Write applications', exact: true }).click()
    assert((await workflowDialog.locator('.project-preview__footer').textContent()).includes('Ready to Draft'))
    await workflowDialog.getByRole('button', { name: 'Attach & save', exact: true }).click()
    assert((await workflowDialog.locator('.project-preview__footer').textContent()).includes('resume attached'))
    await workflowDialog.locator('img').evaluate(img => img.decode())
    await workflowDialog.locator('.project-preview__stage').evaluate(el => { el.scrollLeft = 100 })
    assert(await workflowDialog.locator('.project-preview__stage').evaluate(el => el.scrollLeft) > 0, 'Workflow close-ups must pan horizontally')
    await workflowDialog.locator('.project-preview__stage').evaluate(el => { el.scrollLeft = 0 })
    await page.screenshot({ path: `docs/screenshots/ui-${viewport.width}-workflow-preview.png` })
    await workflowDialog.getByRole('button', { name: 'Close preview', exact: true }).click()
    await page.getByRole('button', { name: 'Preview PH WFH Job Finder — AI Limited Version', exact: true }).click()
    await workflowDialog.getByRole('button', { name: 'Tracker datasheet', exact: true }).click()
    await workflowDialog.locator('img').evaluate(img => img.decode())
    assert((await workflowDialog.locator('.project-preview__footer').textContent()).includes('Ready to Draft'))
    await workflowDialog.getByRole('button', { name: 'Close preview', exact: true }).click()
    await page.getByRole('button', { name: 'Preview Joblink Tracker', exact: true }).click()
    await workflowDialog.locator('img').evaluate(img => img.decode())
    assert((await workflowDialog.locator('img').getAttribute('src')).endsWith('joblink-dashboard.png'))
    await workflowDialog.getByRole('button', { name: 'Explore jobs', exact: true }).click()
    await workflowDialog.locator('img').evaluate(img => img.decode())
    assert((await workflowDialog.locator('img').getAttribute('src')).endsWith('joblink-jobs.png'))
    await workflowDialog.getByRole('button', { name: 'News & events', exact: true }).click()
    await workflowDialog.locator('img').evaluate(img => img.decode())
    assert((await workflowDialog.locator('img').getAttribute('src')).endsWith('joblink-news.png'))
    assert.equal(await workflowDialog.getByRole('link', { name: 'Visit Joblink Tracker' }).getAttribute('href'), 'https://joblink-tracker-c8zm.vercel.app/')
    await workflowDialog.getByRole('button', { name: 'Mobile', exact: true }).click()
    await workflowDialog.locator('img').evaluate(img => img.decode())
    assert((await workflowDialog.locator('img').getAttribute('src')).endsWith('joblink-mobile.png'))
    await workflowDialog.getByRole('button', { name: 'Close preview', exact: true }).click()
    await page.reload({ waitUntil: 'networkidle' })
    await page.getByRole('heading', { name: 'Projects built to be useful.' }).waitFor()
    assert.equal(await page.locator('.portfolio-card').count(), 7)
    await wheelAtContent(750)
    assert(await scroll() > 0, 'Projects must scroll after navigating from Home')
    const projectButton = page.getByRole('button', { name: 'Preview Pet Shop Business Card', exact: true })
    await projectButton.scrollIntoViewIfNeeded()
    const savedPosition = await scroll()
    await projectButton.click()
    const dialog = page.locator('dialog.project-preview')
    await dialog.waitFor()
    const image = dialog.locator('.project-preview__image img')
    await image.evaluate(img => img.decode())
    assert((await image.getAttribute('src')).endsWith('pet-shop-front.svg'))
    await dialog.getByRole('button', { name: 'Back side', exact: true }).click()
    assert((await image.getAttribute('src')).endsWith('pet-shop-back.svg'), 'Frame selection must work')
    await dialog.getByRole('button', { name: 'Zoom in', exact: true }).click()
    await dialog.getByRole('button', { name: 'Reset image zoom' }).filter({ hasText: '125%' }).waitFor()
    await dialog.getByRole('button', { name: 'Reset image zoom' }).click()
    await page.screenshot({ path: `docs/screenshots/ui-${viewport.width}-pet-preview.png` })
    await page.mouse.move(4, 4)
    await page.mouse.wheel(0, 700)
    await page.waitForTimeout(250)
    assert(Math.abs(await scroll() - savedPosition) < 3, 'Background must stay fixed while preview is open')
    await page.keyboard.press('Escape')
    await dialog.waitFor({ state: 'hidden' })
    assert(await projectButton.evaluate(el => el === document.activeElement), 'Closing must restore focus')
    assert(Math.abs(await scroll() - savedPosition) < 3, 'Closing must preserve scroll position')
    const restaurant = page.getByRole('button', { name: 'Preview Restaurant App', exact: true })
    await restaurant.click()
    await dialog.locator('img').evaluate(img => img.decode())
    await dialog.getByRole('button', { name: 'Sushi menu', exact: true }).click()
    await dialog.locator('img').evaluate(img => img.decode())
    assert((await dialog.locator('img').getAttribute('src')).endsWith('restaurant-sushi.svg'))
    await page.screenshot({ path: `docs/screenshots/ui-${viewport.width}-restaurant-preview.png` })
    await dialog.getByRole('button', { name: 'Back', exact: true }).click()
    await page.getByRole('link', { name: 'Back to home', exact: true }).click()
    await page.locator('a[href="/showcase"]:visible').first().click()
    await page.getByRole('heading', { name: 'A closer look at my work.' }).waitFor()
    await wheelAtContent(900)
    assert(await scroll() > 0, 'Showcase must scroll after navigating from Home')
    await page.getByRole('button', { name: 'Preview FU Media', exact: true }).click()
    assert((await page.locator('dialog.project-preview').locator('iframe').getAttribute('src')).includes('Q8s3rW9jc6Q'))
    await page.getByRole('button', { name: 'Close preview', exact: true }).click()
    await page.goto('http://127.0.0.1:5178/services', { waitUntil: 'networkidle' })
    await page.getByRole('heading', { name: 'n8n Automation', exact: true }).waitFor()
    await page.goto('http://127.0.0.1:5178/contact', { waitUntil: 'networkidle' })
    await page.locator('.cgrid__socials').waitFor()
    assert.equal(await page.locator('.cgrid__social').count(), 4)
    await page.locator('a[href="/"]:visible').first().click()
    await page.locator('a[href="/projects"]:visible').first().click()
    await page.getByRole('heading', { name: 'Projects built to be useful.' }).waitFor()
    await page.locator('.portfolio-card img').evaluateAll(async images => { images.forEach(img => img.loading = 'eager'); await Promise.all(images.map(img => img.decode())) })
    await page.screenshot({ path: `docs/screenshots/ui-${viewport.width}-projects.png`, fullPage: viewport.width < 1100 })
    await page.getByRole('button', { name: 'Preview Pet Shop Business Card', exact: true }).scrollIntoViewIfNeeded()
    await page.waitForTimeout(250)
    await page.screenshot({ path: `docs/screenshots/ui-${viewport.width}-design-cards.png` })
    assert(await page.evaluate(() => {
      const cards = [...document.querySelectorAll('.portfolio-card')]
      const lastBottom = Math.max(...cards.map(card => card.getBoundingClientRect().bottom))
      return document.querySelector('.portfolio-upwork').getBoundingClientRect().top >= lastBottom + 20
    }), 'The Upwork footer must have clear space below the project cards')
    await page.getByRole('button', { name: 'Preview 5S Plumbing', exact: true }).click()
    await page.locator('dialog.project-preview').locator('img').evaluate(img => img.decode())
    await page.mouse.click(3, 3)
    await page.locator('dialog.project-preview').waitFor({ state: 'hidden' })
    await page.evaluate(() => { document.documentElement.dataset.theme = 'dark' })
    await page.getByRole('button', { name: 'Preview Pet Shop Business Card', exact: true }).click()
    await page.locator('dialog.project-preview').locator('img').evaluate(img => img.decode())
    await page.waitForTimeout(350)
    await page.screenshot({ path: `docs/screenshots/ui-${viewport.width}-dark-preview.png` })
    await page.getByRole('button', { name: 'Close preview', exact: true }).click()
    await page.close()
    console.log(`${viewport.width}px: route scrolling, galleries, zoom, back, Escape, backdrop, focus and scroll restoration passed`)
  }
  assert.deepEqual(errors, [], 'No browser runtime errors')
} finally {
  await browser.close()
}
